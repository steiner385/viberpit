def _parse_string_tuple(
    payload: Mapping[str, Any], key: str, what: str, default: tuple[str, ...]
) -> tuple[str, ...]:
    if key not in payload or payload[key] is None:
        return default
    value = payload[key]
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise CodexSchemaError(f"{what} field {key!r} must be an array of strings")
    return tuple(value)


def parse_model(payload: Any) -> Model:
    what = "model/list model"
    body = _as_mapping(payload, what)
    raw_efforts = body.get("supportedReasoningEfforts")
    if not isinstance(raw_efforts, list):
        raise CodexSchemaError(f"{what} field 'supportedReasoningEfforts' must be an array")
    efforts: list[ReasoningEffortOption] = []
    for option in raw_efforts:
        option_body = _as_mapping(option, f"{what} reasoning effort")
        efforts.append(
            ReasoningEffortOption(
                reasoning_effort=_require_str(
                    option_body, "reasoningEffort", f"{what} reasoning effort"
                ),
                description=_require_str(
                    option_body, "description", f"{what} reasoning effort"
                ),
            )
        )
    raw_tiers = body.get("serviceTiers")
    tier_ids: tuple[str, ...] = ()
    if raw_tiers is not None:
        if not isinstance(raw_tiers, list):
            raise CodexSchemaError(f"{what} field 'serviceTiers' must be an array")
        tier_ids = tuple(
            _require_str(_as_mapping(tier, f"{what} service tier"), "id", f"{what} service tier")
            for tier in raw_tiers
        )
    return Model(
        id=_require_str(body, "id", what),
        model=_require_str(body, "model", what),
        display_name=_require_str(body, "displayName", what),
        description=_require_str(body, "description", what),
        hidden=_require_bool(body, "hidden", what),
        is_default=_require_bool(body, "isDefault", what),
        default_reasoning_effort=_require_str(body, "defaultReasoningEffort", what),
        supported_reasoning_efforts=tuple(efforts),
        input_modalities=_parse_string_tuple(
            body, "inputModalities", what, DEFAULT_INPUT_MODALITIES
        ),
        service_tier_ids=tier_ids,
        default_service_tier=_optional_str(body, "defaultServiceTier", what),
    )


def parse_model_list_response(payload: Any) -> ModelListResponse:
    what = "model/list response"
    body = _as_mapping(payload, what)
    data = body.get("data")
    if not isinstance(data, list):
        raise CodexSchemaError(f"{what} field 'data' must be an array")
    return ModelListResponse(
        data=tuple(parse_model(item) for item in data),
        next_cursor=_optional_str(body, "nextCursor", what),
    )


