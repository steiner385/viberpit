class CodexSchemaError(ValueError):
    """An inbound or outbound payload violated the pinned contract.

    Messages carry field and method names only — never a wire value.
    """


# ---------------------------------------------------------------------------
# Contract extraction and drift
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True, repr=False)
class Contract:
    """One observed or committed app-server schema contract."""

    documents: Mapping[str, Any]
    method_index: Mapping[str, tuple[str, ...]]
    envelope_sha256: Mapping[str, str] = field(default_factory=dict)

    @property
    def sha256(self) -> str:
        return contract_sha256(self.documents, self.method_index)


def contract_sha256(
    documents: Mapping[str, Any],
    method_index: Mapping[str, Sequence[str]],
) -> str:
    """Hash the canonicalized curated subset plus the full method inventory."""
    canonical = json.dumps(
        {
            "documents": dict(documents),
            "methodIndex": {key: sorted(value) for key, value in method_index.items()},
        },
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def envelope_methods(document: Any) -> tuple[str, ...]:
    """Read the method-name inventory out of one JSON-RPC envelope schema."""
    if not isinstance(document, Mapping):
        raise CodexSchemaError("envelope schema is not an object")
    variants = document.get("oneOf")
    if not isinstance(variants, list) or not variants:
        raise CodexSchemaError("envelope schema declares no method variants")
    methods: set[str] = set()
    for variant in variants:
        if not isinstance(variant, Mapping):
            raise CodexSchemaError("envelope schema variant is not an object")
        properties = variant.get("properties")
        if not isinstance(properties, Mapping):
            raise CodexSchemaError("envelope schema variant declares no properties")
        method = properties.get("method")
        names = method.get("enum") if isinstance(method, Mapping) else None
        if not isinstance(names, list) or len(names) != 1 or not isinstance(names[0], str):
            raise CodexSchemaError("envelope schema variant declares no single method")
        methods.add(names[0])
    return tuple(sorted(methods))


def fixture_filename(upstream_path: str) -> str:
    """Map an upstream relative schema path to its flat fixture filename."""
    return upstream_path.replace("/", "__")


def _read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise CodexSchemaError(f"schema file is unreadable: {path.name}") from exc
    except json.JSONDecodeError as exc:
        raise CodexSchemaError(f"schema file is not valid JSON: {path.name}") from exc


def extract_contract(generated_root: Path) -> Contract:
    """Read a freshly generated ``generate-json-schema`` directory into a Contract."""
    documents: dict[str, Any] = {}
    for relative in CURATED_SCHEMA_FILES:
        path = generated_root / relative
        if not path.is_file():
            raise CodexSchemaError(f"generated schema is missing {relative}")
        documents[relative] = _read_json(path)

    method_index: dict[str, tuple[str, ...]] = {}
    envelope_sha256: dict[str, str] = {}
    for relative, key in ENVELOPE_SCHEMA_FILES.items():
        path = generated_root / relative
        if not path.is_file():
            raise CodexSchemaError(f"generated schema is missing {relative}")
        raw = path.read_bytes()
        envelope_sha256[relative] = hashlib.sha256(raw).hexdigest()
        method_index[key] = envelope_methods(json.loads(raw.decode("utf-8")))
    return Contract(documents, method_index, envelope_sha256)


def load_pinned_fixture_contract(fixture_root: Path) -> Contract:
    """Read the committed flat fixture directory back into a Contract."""
    manifest = _read_json(fixture_root / MANIFEST_FILENAME)
    if not isinstance(manifest, Mapping):
        raise CodexSchemaError("fixture manifest is not an object")
    upstream_paths = manifest.get("documents")
    if not isinstance(upstream_paths, list) or not all(
        isinstance(item, str) for item in upstream_paths
    ):
        raise CodexSchemaError("fixture manifest declares no document list")
    documents = {
        relative: _read_json(fixture_root / fixture_filename(relative))
        for relative in upstream_paths
    }
    raw_index = _read_json(fixture_root / METHOD_INDEX_FILENAME)
    if not isinstance(raw_index, Mapping):
        raise CodexSchemaError("fixture method index is not an object")
    method_index: dict[str, tuple[str, ...]] = {}
    for key in ENVELOPE_SCHEMA_FILES.values():
        names = raw_index.get(key)
        if not isinstance(names, list) or not all(isinstance(n, str) for n in names):
            raise CodexSchemaError(f"fixture method index is missing {key}")
        method_index[key] = tuple(sorted(names))
    raw_envelopes = manifest.get("envelopes")
    envelope_sha256 = (
        {
            str(name): str(entry.get("sha256"))
            for name, entry in raw_envelopes.items()
            if isinstance(entry, Mapping)
        }
        if isinstance(raw_envelopes, Mapping)
        else {}
    )
    return Contract(documents, method_index, envelope_sha256)


class ContractDriftReason(StrEnum):
    """Typed reason a live app-server no longer matches the pinned contract."""

    CLI_VERSION = "cli_version_mismatch"
    CONTRACT_HASH = "contract_hash_mismatch"


@dataclass(frozen=True, slots=True, repr=False)
class ContractDrift:
    """A structured, non-raising report that the boundary moved under us."""

    reasons: tuple[ContractDriftReason, ...]
    expected_cli_version: str
    observed_cli_version: str
    expected_contract_sha256: str
    observed_contract_sha256: str

    def reason_codes(self) -> tuple[str, ...]:
        return tuple(reason.value for reason in self.reasons)

    def __str__(self) -> str:
        return "codex app-server contract drift (" + ", ".join(self.reason_codes()) + ")"


def check_contract(*, cli_version: str, contract_sha256: str) -> ContractDrift | None:
    """Compare a runtime observation against the pin.

    Returns ``None`` when the observation matches, and a typed
    :class:`ContractDrift` otherwise. Callers decide the policy — this never
    raises, so a version bump degrades Codex availability instead of crashing a
    daemon that is also serving Claude sessions.
    """
    reasons: list[ContractDriftReason] = []
    if cli_version != PINNED_CLI_VERSION:
        reasons.append(ContractDriftReason.CLI_VERSION)
    if contract_sha256 != PINNED_CONTRACT_SHA256:
        reasons.append(ContractDriftReason.CONTRACT_HASH)
    if not reasons:
        return None
    return ContractDrift(
        reasons=tuple(reasons),
        expected_cli_version=PINNED_CLI_VERSION,
        observed_cli_version=cli_version,
        expected_contract_sha256=PINNED_CONTRACT_SHA256,
        observed_contract_sha256=contract_sha256,
    )


# ---------------------------------------------------------------------------
# Validation helpers
#
# Unknown *fields* are ignored everywhere (forward compatibility); unknown or
# wrong-typed *required* fields raise. `bool` is an `int` subclass, so integer
# checks use an explicit type test.
# ---------------------------------------------------------------------------


def _as_mapping(payload: Any, what: str) -> Mapping[str, Any]:
    if not isinstance(payload, Mapping):
        raise CodexSchemaError(f"{what} is not an object")
    return payload


def _require_str(payload: Mapping[str, Any], key: str, what: str) -> str:
    value = payload.get(key)
    if not isinstance(value, str) or not value:
        raise CodexSchemaError(f"{what} field {key!r} must be a non-empty string")
    return value


def _optional_str(payload: Mapping[str, Any], key: str, what: str) -> str | None:
    if key not in payload or payload[key] is None:
        return None
    value = payload[key]
    if not isinstance(value, str):
        raise CodexSchemaError(f"{what} field {key!r} must be a string or null")
    return value


def _optional_enum(
    payload: Mapping[str, Any],
    key: str,
    what: str,
    allowed: frozenset[str],
) -> str | None:
    value = _optional_str(payload, key, what)
    if value is not None and value not in allowed:
        raise CodexSchemaError(f"{what} field {key!r} has an unsupported value")
    return value


def _require_enum(
    payload: Mapping[str, Any],
    key: str,
    what: str,
    allowed: frozenset[str],
) -> str:
    value = _require_str(payload, key, what)
    if value not in allowed:
        raise CodexSchemaError(f"{what} field {key!r} has an unsupported value")
    return value


def _require_present_optional_str(
    payload: Mapping[str, Any], key: str, what: str
) -> str | None:
    """A required field that is explicitly nullable (e.g. ChatgptAccount.email)."""
    if key not in payload:
        raise CodexSchemaError(f"{what} field {key!r} is required")
    return _optional_str(payload, key, what)


def _require_bool(payload: Mapping[str, Any], key: str, what: str) -> bool:
    value = payload.get(key)
    if not isinstance(value, bool):
        raise CodexSchemaError(f"{what} field {key!r} must be a boolean")
    return value


def _optional_bool(payload: Mapping[str, Any], key: str, what: str) -> bool | None:
    if key not in payload or payload[key] is None:
        return None
    value = payload[key]
    if not isinstance(value, bool):
        raise CodexSchemaError(f"{what} field {key!r} must be a boolean or null")
    return value


def _require_int(payload: Mapping[str, Any], key: str, what: str) -> int:
    value = payload.get(key)
    if type(value) is not int:
        raise CodexSchemaError(f"{what} field {key!r} must be an integer")
    return value


def _optional_int(payload: Mapping[str, Any], key: str, what: str) -> int | None:
    if key not in payload or payload[key] is None:
        return None
    value = payload[key]
    if type(value) is not int:
        raise CodexSchemaError(f"{what} field {key!r} must be an integer or null")
    return value


def _optional_float(payload: Mapping[str, Any], key: str, what: str) -> float | None:
    """A JSON ``number`` field. Accepts an integer literal (JSON has one numeric
    type, so a whole-valued double arrives as ``int``) but never a ``bool``, which
    is an ``int`` subclass and would otherwise read as 0.0/1.0."""
    if key not in payload or payload[key] is None:
        return None
    value = payload[key]
    if type(value) not in (int, float):
        raise CodexSchemaError(f"{what} field {key!r} must be a number or null")
    return float(value)


def _optional_redacted(
    payload: Mapping[str, Any], key: str, what: str
) -> Redacted | None:
    value = _optional_str(payload, key, what)
    return None if value is None else Redacted(value)


def _reject_unknown_fields(
    payload: Mapping[str, Any], allowed: frozenset[str], what: str
) -> None:
    if any(not isinstance(key, str) or key not in allowed for key in payload):
        raise CodexSchemaError(f"{what} contains unsupported fields")


