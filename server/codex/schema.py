@dataclass(frozen=True, slots=True)
class ExternalAuthLoginParams:
    """`account/login/start` with host-supplied ChatGPT tokens.

    Both credential fields are :class:`Redacted`, so the dataclass `repr` — and
    anything that formats it, including a traceback frame dump — is safe.
    """

    access_token: Redacted
    chatgpt_account_id: Redacted
    chatgpt_plan_type: str | None = None

    def __post_init__(self) -> None:
        if not self.access_token:
            raise CodexSchemaError("account/login/start requires a non-empty accessToken")
        if not self.chatgpt_account_id:
            raise CodexSchemaError(
                "account/login/start requires a non-empty chatgptAccountId"
            )
        if self.chatgpt_plan_type is not None and not self.chatgpt_plan_type:
            raise CodexSchemaError(
                "account/login/start chatgptPlanType must be null or non-empty"
            )

    def to_wire(self) -> dict[str, Any]:
        wire: dict[str, Any] = {
            "type": EXTERNAL_AUTH_LOGIN_TYPE,
            "accessToken": self.access_token.reveal(),
            "chatgptAccountId": self.chatgpt_account_id.reveal(),
        }
        if self.chatgpt_plan_type is not None:
            wire["chatgptPlanType"] = self.chatgpt_plan_type
        return wire


