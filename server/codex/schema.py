def parse_rate_limits_response(payload: Any) -> GetAccountRateLimitsResponse:
    what = "account/rateLimits/read response"
    body = _as_mapping(payload, what)
    if "rateLimits" not in body or body["rateLimits"] is None:
        raise CodexSchemaError(f"{what} field 'rateLimits' is required")
    buckets: dict[str, RateLimitSnapshot] = {}
    raw_buckets = body.get("rateLimitsByLimitId")
    if raw_buckets is not None:
        if not isinstance(raw_buckets, Mapping):
            raise CodexSchemaError(f"{what} field 'rateLimitsByLimitId' must be an object")
        for key, snapshot in raw_buckets.items():
            buckets[str(key)] = parse_rate_limit_snapshot(snapshot, what)
    return GetAccountRateLimitsResponse(
        rate_limits=parse_rate_limit_snapshot(body["rateLimits"], what),
        account_id=_optional_redacted(body, "accountId", what),
        rate_limits_by_limit_id=buckets,
    )


