def _parse_codex_error_info(value: Any, what: str) -> str | None:
    """Reduce the CodexErrorInfo union to its variant name.

    The union is either a bare string enum or a single-key object such as
    ``{"httpConnectionFailed": {...}}``; only the discriminator is retained.
    """
    if value is None:
        return None
    if isinstance(value, str):
        category = value
    elif isinstance(value, Mapping) and len(value) == 1:
        category = str(next(iter(value)))
    else:
        raise CodexSchemaError(f"{what} field 'codexErrorInfo' has an unknown shape")
    if category not in CODEX_ERROR_INFO_CATEGORIES:
        raise CodexSchemaError(f"{what} field 'codexErrorInfo' has an unknown category")
    return category


def _parse_error_notification(payload: Any) -> ErrorNotificationParams:
    what = "error notification"
    body = _as_mapping(payload, what)
    error = _as_mapping(body.get("error"), f"{what} error")
    details = _optional_str(error, "additionalDetails", f"{what} error")
    return ErrorNotificationParams(
        message=Redacted(_require_str(error, "message", f"{what} error")),
        thread_id=Redacted(_require_str(body, "threadId", what)),
        turn_id=Redacted(_require_str(body, "turnId", what)),
        will_retry=_require_bool(body, "willRetry", what),
        codex_error_info=_parse_codex_error_info(
            error.get("codexErrorInfo"), f"{what} error"
        ),
        additional_details=None if details is None else Redacted(details),
    )


def parse_server_notification(method: str, payload: Any) -> ServerNotificationParams:
    """Parse one supported server notification into its DTO.

    Unsupported methods raise; `protocol.py` counts and drops them rather than
    calling this, so a new upstream notification can never crash a session.
    """
    if method == "error":
        return _parse_error_notification(payload)
    if method == "account/updated":
        what = "account/updated notification"
        body = _as_mapping(payload, what)
        return AccountUpdatedParams(
            auth_mode=_optional_enum(body, "authMode", what, AUTH_MODES),
            plan_type=_optional_enum(body, "planType", what, PLAN_TYPES),
        )
    if method == "account/rateLimits/updated":
        what = "account/rateLimits/updated notification"
        body = _as_mapping(payload, what)
        if "rateLimits" not in body or body["rateLimits"] is None:
            raise CodexSchemaError(f"{what} field 'rateLimits' is required")
        return AccountRateLimitsUpdatedParams(
            snapshot=parse_rate_limit_snapshot(body["rateLimits"], what)
        )
    if method == "account/login/completed":
        what = "account/login/completed notification"
        body = _as_mapping(payload, what)
        return AccountLoginCompletedParams(
            success=_require_bool(body, "success", what),
            login_id=_optional_redacted(body, "loginId", what),
            error=_optional_redacted(body, "error", what),
        )
    if method == METHOD_THREAD_STARTED:
        what = "thread/started notification"
        body = _as_mapping(payload, what)
        return ThreadStartedParams(
            thread=parse_thread(body.get("thread"), f"{what} thread")
        )
    if method == METHOD_THREAD_STATUS_CHANGED:
        what = "thread/status/changed notification"
        body = _as_mapping(payload, what)
        return ThreadStatusChangedParams(
            thread_id=_require_str(body, "threadId", what),
            status=parse_thread_status(body.get("status"), f"{what} status"),
        )
    if method == METHOD_THREAD_TOKEN_USAGE_UPDATED:
        what = "thread/tokenUsage/updated notification"
        body = _as_mapping(payload, what)
        return ThreadTokenUsageUpdatedParams(
            thread_id=_require_str(body, "threadId", what),
            turn_id=_require_str(body, "turnId", what),
            token_usage=parse_thread_token_usage(
                body.get("tokenUsage"), f"{what} tokenUsage"
            ),
        )
    if method in (METHOD_TURN_STARTED, METHOD_TURN_COMPLETED):
        what = f"{method} notification"
        body = _as_mapping(payload, what)
        thread_id = _require_str(body, "threadId", what)
        turn = parse_turn(body.get("turn"), f"{what} turn")
        if method == METHOD_TURN_STARTED:
            return TurnStartedParams(thread_id=thread_id, turn=turn)
        return TurnCompletedParams(thread_id=thread_id, turn=turn)
    if method == METHOD_ITEM_STARTED:
        what = "item/started notification"
        body = _as_mapping(payload, what)
        return ItemStartedParams(
            thread_id=_require_str(body, "threadId", what),
            turn_id=_require_str(body, "turnId", what),
            item=parse_thread_item(body.get("item")),
            started_at_ms=_require_int(body, "startedAtMs", what),
        )
    if method == METHOD_ITEM_COMPLETED:
        what = "item/completed notification"
        body = _as_mapping(payload, what)
        return ItemCompletedParams(
            thread_id=_require_str(body, "threadId", what),
            turn_id=_require_str(body, "turnId", what),
            item=parse_thread_item(body.get("item")),
            completed_at_ms=_require_int(body, "completedAtMs", what),
        )
    if method == METHOD_ITEM_AGENT_MESSAGE_DELTA:
        what = "item/agentMessage/delta notification"
        body = _as_mapping(payload, what)
        return AgentMessageDeltaParams(
            thread_id=_require_str(body, "threadId", what),
            turn_id=_require_str(body, "turnId", what),
            item_id=_require_str(body, "itemId", what),
            delta=_require_present_optional_str(body, "delta", what) or "",
        )
    if method == METHOD_ITEM_REASONING_SUMMARY_TEXT_DELTA:
        what = "item/reasoning/summaryTextDelta notification"
        body = _as_mapping(payload, what)
        return ReasoningSummaryTextDeltaParams(
            thread_id=_require_str(body, "threadId", what),
            turn_id=_require_str(body, "turnId", what),
            item_id=_require_str(body, "itemId", what),
            delta=_require_present_optional_str(body, "delta", what) or "",
            summary_index=_require_int(body, "summaryIndex", what),
        )
    if method == METHOD_ITEM_COMMAND_EXECUTION_OUTPUT_DELTA:
        what = "item/commandExecution/outputDelta notification"
        body = _as_mapping(payload, what)
        return CommandExecutionOutputDeltaParams(
            thread_id=_require_str(body, "threadId", what),
            turn_id=_require_str(body, "turnId", what),
            item_id=_require_str(body, "itemId", what),
            delta=_require_present_optional_str(body, "delta", what) or "",
        )
    raise CodexSchemaError(
        "unsupported server notification: "
        + unknown_notification_label(method)
    )


def unknown_notification_label(method: str, declared: Iterable[str] | None = None) -> str:
    """Bucket an unsupported notification method for counters.

    Declared upstream methods keep their name (they are part of the pinned
    contract and carry no user data); anything else — including a hostile method
    string — collapses to one fixed label so a counter key can never leak.
    """
    known = DECLARED_SERVER_NOTIFICATIONS if declared is None else frozenset(declared)
    return method if method in known else "<unrecognized>"


