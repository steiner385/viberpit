import json
from pathlib import Path

from server.sessions.titles import read_ai_title, read_user_prompts_from_file


def _write(root: Path, sid: str, lines: list[dict], sub: str = "encoded-cwd"):
    d = root / "projects" / sub
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{sid}.jsonl").write_text("\n".join(json.dumps(x) for x in lines))


def test_user_prompts_skip_cli_local_command_records(tmp_path):
    """``driver.set_model()`` makes the CLI write its own ``/model`` bookkeeping into
    the transcript as ``type:"user"`` entries — the caveat, ``<command-name>`` and
    ``<local-command-stdout>`` — of which only the caveat is flagged ``isMeta``.
    None is a human prompt, so the fallback titler must not summarise them: this is
    how a fresh Fable session was named "Set model to Fable" instead of after its
    real prompt (2026-09-02). The interrupt marker is CLI plumbing too."""
    rows = [
        {"type": "user", "isMeta": True, "message": {"role": "user", "content":
            "<local-command-caveat>Caveat: The messages below were generated by the "
            "user while running local commands.</local-command-caveat>"}},
        {"type": "user", "message": {"role": "user", "content":
            "<command-name>/model</command-name>\n<command-message>model"
            "</command-message>\n<command-args>fable</command-args>"}},
        {"type": "user", "message": {"role": "user", "content":
            "<local-command-stdout>Set model to fable (claude-fable-5)"
            "</local-command-stdout>"}},
        {"type": "user", "message": {"role": "user", "content": "[Request interrupted by user]"}},
        {"type": "user", "message": {"role": "user", "content": "audit the landing page"}},
    ]
    _write(tmp_path, "sid-model", rows)
    path = tmp_path / "projects" / "encoded-cwd" / "sid-model.jsonl"
    assert read_user_prompts_from_file(path) == ["audit the landing page"]


def test_reads_ai_title(tmp_path):
    _write(tmp_path, "sid1", [
        {"type": "user", "message": {"content": "hi"}},
        {"ai-title": "Fix the login bug"},
    ])
    assert read_ai_title(tmp_path, "sid1") == "Fix the login bug"


def test_custom_title_wins_over_ai_title(tmp_path):
    _write(tmp_path, "sid2", [
        {"ai-title": "auto title"},
        {"customTitle": "My Renamed Session"},
    ])
    assert read_ai_title(tmp_path, "sid2") == "My Renamed Session"


def test_summary_key_supported(tmp_path):
    _write(tmp_path, "sid4", [{"type": "summary", "summary": "Refactor parser"}])
    assert read_ai_title(tmp_path, "sid4") == "Refactor parser"


def test_missing_file_returns_none(tmp_path):
    assert read_ai_title(tmp_path, "nope") is None


def test_empty_session_id_returns_none(tmp_path):
    assert read_ai_title(tmp_path, "") is None


def test_malformed_lines_do_not_raise(tmp_path):
    d = tmp_path / "projects" / "x"
    d.mkdir(parents=True)
    (d / "sid3.jsonl").write_text('{not json\n{"ai-title": "ok"}\n')
    assert read_ai_title(tmp_path, "sid3") == "ok"
